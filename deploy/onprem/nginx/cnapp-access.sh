#!/bin/sh
# Renders the on-prem access policy for nginx at container start (mounted as
# /docker-entrypoint.d/25-cnapp-access.sh by docker-compose.prod.yml; runs after
# the image's envsubst step). Settings come from cnapp.env via the compose file,
# so `cnapp-ctl public-agent enable|disable` only has to recreate the container.
#
#   CNAPP_INTERNAL_CIDRS   who may use the dashboard and the user API
#                          (CNAPP_ALLOWED_CIDRS + CNAPP_ADMIN_CIDRS + the Docker
#                          network; 127.0.0.0/8 is always added)
#   CNAPP_PUBLIC_AGENT     true: the firewall lets anyone reach 443 (cnapp-ctl)
#   CNAPP_AGENT_HOSTNAME   optional dedicated agent name (server block that serves
#                          /api/agent/ only; tls/agent.crt|key if present, else server.crt)
#   CNAPP_AGENT_RATE / _BURST, CNAPP_AGENT_ENROLL_RATE / _BURST, CNAPP_AGENT_CONN_LIMIT
#   CNAPP_PUBLIC_SENSOR_INGEST  true: POST /api/runtime/events is reachable from anywhere too
#   RELAY_URL              the remote-session relay, agent listener (WebSockets; http://relay:8001)
#   RELAY_VIEWER_URL       its viewer listener (used by onprem.conf.template; http://relay:8002)
#   SITE_HOSTNAMES         optional public website names, e.g. "travound.com www.travound.com"
#                          (cnapp-ctl site enable): the static site baked into the image
#                          (/usr/share/nginx/site) plus POST /api/contact, for any client; the
#                          first name is canonical (the others redirect to it);
#                          tls/site.crt|key if present, else server.crt
#   SITE_CONSOLE_URL       where the site's "Log in" links point (default https://CNAPP_HOSTNAME)
#
# Policy: /api/agent/* is reachable from anywhere (rate limited per external IP);
# everything else answers 404 to clients outside CNAPP_INTERNAL_CIDRS. The website
# names (when set) serve only the website and POST /api/contact, to everyone.
set -eu

out=/etc/nginx/conf.d
log_dir=/var/log/cnapp
me=25-cnapp-access

fail() { echo "$me: ERROR: $*" >&2; exit 1; }
num() { case $2 in ''|*[!0-9]*) fail "$1 must be a number (got '$2')" ;; esac; }
rate() { echo "$2" | grep -Eq '^[0-9]+r/[sm]$' || fail "$1 must look like 20r/s or 30r/m (got '$2')"; }

rate_v=${CNAPP_AGENT_RATE:-20r/s};             rate CNAPP_AGENT_RATE "$rate_v"
burst_v=${CNAPP_AGENT_BURST:-200};             num CNAPP_AGENT_BURST "$burst_v"
erate_v=${CNAPP_AGENT_ENROLL_RATE:-60r/m};     rate CNAPP_AGENT_ENROLL_RATE "$erate_v"
eburst_v=${CNAPP_AGENT_ENROLL_BURST:-100};     num CNAPP_AGENT_ENROLL_BURST "$eburst_v"
conn_v=${CNAPP_AGENT_CONN_LIMIT:-200};         num CNAPP_AGENT_CONN_LIMIT "$conn_v"
backend=${BACKEND_URL:-http://backend:8000}
echo "$backend" | grep -Eq '^https?://[A-Za-z0-9.:_-]+/?$' || fail "invalid BACKEND_URL"
relay=${RELAY_URL:-http://relay:8001}
echo "$relay" | grep -Eq '^https?://[A-Za-z0-9.:_-]+/?$' || fail "invalid RELAY_URL"
# The viewer listener is used by onprem.conf.template; checked here so a bad value fails loudly.
echo "${RELAY_VIEWER_URL:-http://relay:8002}" | grep -Eq '^https?://[A-Za-z0-9.:_-]+/?$' || fail "invalid RELAY_VIEWER_URL"
public=${CNAPP_PUBLIC_AGENT:-false}
agent_host=${CNAPP_AGENT_HOSTNAME:-}
main_host=${CNAPP_HOSTNAME:-}
if [ -n "$agent_host" ]; then
  echo "$agent_host" | grep -Eq '^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$' || fail "invalid CNAPP_AGENT_HOSTNAME"
fi
# Public website names: lower-cased, de-duplicated, never the console or agent name.
lc() { echo "$1" | tr '[:upper:]' '[:lower:]'; }
site_names=""
set -f  # no globbing of the names
for h in $(lc "${SITE_HOSTNAMES:-}" | tr ',;' '  '); do
  echo "$h" | grep -Eq '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$' \
    || fail "invalid name in SITE_HOSTNAMES: $h (DNS names only)"
  echo "$h" | grep -Eq '^[0-9.]+$' && fail "invalid name in SITE_HOSTNAMES: $h (DNS names only)"
  if [ "$h" = "$(lc "$main_host")" ] || [ "$h" = "$(lc "$agent_host")" ]; then
    fail "SITE_HOSTNAMES must not contain the console or agent hostname ($h)"
  fi
  case " $site_names " in *" $h "*) continue ;; esac
  site_names="${site_names:+$site_names }$h"
done
set +f
console_url=${SITE_CONSOLE_URL:-https://$main_host}
console_url=${console_url%/}
if [ -n "$site_names" ]; then
  echo "$console_url" | grep -Eq '^https://[A-Za-z0-9.-]+(:[0-9]{1,5})?$' || fail "invalid SITE_CONSOLE_URL (https://NAME[:PORT])"
fi

# ---------------------------------------------------------------- http level
{
  echo "# Generated by $me at container start - do not edit."
  echo "# Internal networks: full access. Everyone else: /api/agent/ only."
  echo "geo \$cnapp_internal {"
  echo "  default 0;"
  echo "  127.0.0.0/8 1;"
  echo "  ::1 1;"
  for c in $(echo "${CNAPP_INTERNAL_CIDRS:-}" | tr ',; ' '   '); do
    echo "$c" | grep -Eq '^[0-9A-Fa-f:.]+(/[0-9]{1,3})?$' || fail "invalid CIDR in CNAPP_INTERNAL_CIDRS: $c"
    case $c in 127.0.0.0/8|::1) continue ;; esac  # always present
    echo "  $c 1;"
  done
  cat <<'EOF'
}

# Agent API paths, checked on the raw request line: plain segments only (no
# dot-segments, no percent-encoding), so the URI the backend receives is the one
# that was allowed.
map $request_uri $cnapp_agent_path {
  default 0;
  "~^/api/agent/[A-Za-z0-9_-]+(?:[./][A-Za-z0-9_-]+)*/?(?:\?|$)" 1;
EOF
  # Runtime sensors outside the internal networks (bearer-token protected): opt-in.
  if [ "${CNAPP_PUBLIC_SENSOR_INGEST:-false}" = true ]; then
    echo '  "~^/api/runtime/events/?(?:\?|$)" 1;'
  fi
  cat <<'EOF'
}
map "$cnapp_internal$cnapp_agent_path" $cnapp_block {
  "00"    1;
  default 0;
}
map $cnapp_block $cnapp_access {
  1       blocked;
  default allowed;
}
# Only external clients are rate limited / connection limited (an empty key is
# not counted) and logged to the edge log that fail2ban reads.
map $cnapp_internal $cnapp_agent_limit_key {
  1       "";
  default $binary_remote_addr;
}
map $cnapp_internal $cnapp_log_external {
  1       0;
  default 1;
}
log_format cnapp_edge '$remote_addr - [$time_local] "$request_method $uri $server_protocol" $status '
                      '$body_bytes_sent "$host" "$http_user_agent" $cnapp_access';
# Public website requests (SITE_HOSTNAMES): logged as "site", never as "blocked"
# (fail2ban's cnapp-probe jail must not ban website visitors).
log_format cnapp_edge_site '$remote_addr - [$time_local] "$request_method $uri $server_protocol" $status '
                           '$body_bytes_sent "$host" "$http_user_agent" site';
limit_req_status 429;
limit_conn_status 429;
# WebSocket upgrades (remote sessions: /api/remote/ and /api/agent/remote/ only).
map $http_upgrade $connection_upgrade {
  default upgrade;
  ''      close;
}
EOF
  echo "limit_req_zone \$cnapp_agent_limit_key zone=cnapp_agent:10m rate=$rate_v;"
  echo "limit_req_zone \$cnapp_agent_limit_key zone=cnapp_enroll:2m rate=$erate_v;"
  echo "limit_conn_zone \$cnapp_agent_limit_key zone=cnapp_agent_conn:5m;"
} >"$out/00-cnapp-access.conf"

# ---------------------------------------------------------------- server level (included by every server)
{
  echo "# Generated by $me."
  echo "access_log /var/log/nginx/access.log main;"
  if [ -d "$log_dir" ] && [ -w "$log_dir" ]; then
    echo "access_log $log_dir/edge-access.log cnapp_edge if=\$cnapp_log_external;"
  else
    echo "# $log_dir is not writable: no edge log (fail2ban needs it)"
  fi
  echo "client_header_timeout 15s;"
  echo "keepalive_timeout 30s;"
} >"$out/cnapp-server.inc"

# ---------------------------------------------------------------- agent API locations
proxy_block() {
  cat <<EOF
    if (\$request_method !~ ^(GET|HEAD|POST)\$) { return 405; }
    client_max_body_size 8m;
    client_body_timeout 30s;
    send_timeout 60s;
    limit_conn cnapp_agent_conn $conn_v;
    set \$backend_upstream "$backend";
    proxy_pass \$backend_upstream;
    proxy_http_version 1.1;
    proxy_set_header Host \$host;
    proxy_set_header X-Forwarded-Host \$host;
    # nginx is the edge: overwrite (never append to) client-supplied values.
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$remote_addr;
    proxy_set_header X-Forwarded-Proto https;
    proxy_set_header Cookie "";
    proxy_connect_timeout 10s;
    proxy_read_timeout 120s;
    proxy_send_timeout 120s;
    proxy_hide_header X-Content-Type-Options;
    proxy_hide_header X-Frame-Options;
    proxy_hide_header Referrer-Policy;
    proxy_hide_header Strict-Transport-Security;
EOF
}
{
  echo "# Generated by $me. Endpoint-agent API: reachable from anywhere when the"
  echo "# firewall allows it (CNAPP_PUBLIC_AGENT); per-IP limits for external clients."
  echo "location /api/agent/ {"
  echo "    limit_req zone=cnapp_agent burst=$burst_v nodelay;"
  proxy_block
  echo "}"
  echo "location = /api/agent/enroll {"
  echo "    limit_req zone=cnapp_enroll burst=$eburst_v nodelay;"
  proxy_block
  echo "}"
  cat <<EOF
# Remote sessions: the agent's outbound WebSocket to the single-worker relay
# service (docs/DEVICE_MANAGEMENT.md#remote-sessions-windows). Long timeouts on
# this path only; the relay pings every 20 s and limits message sizes itself.
location ~ "^/api/agent/remote/[0-9a-f]{32}\$" {
    if (\$request_method != GET) { return 405; }
    limit_req zone=cnapp_agent burst=$burst_v nodelay;
    limit_conn cnapp_agent_conn $conn_v;
    set \$relay_upstream "$relay";
    proxy_pass \$relay_upstream;
    proxy_http_version 1.1;
    proxy_set_header Upgrade \$http_upgrade;
    proxy_set_header Connection \$connection_upgrade;
    proxy_set_header Host \$host;
    proxy_set_header X-Forwarded-Host \$host;
    # nginx is the edge: overwrite (never append to) client-supplied values.
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$remote_addr;
    proxy_set_header X-Forwarded-Proto https;
    proxy_set_header Cookie "";
    proxy_buffering off;
    proxy_connect_timeout 10s;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
}
EOF
} >"$out/cnapp-agent-locations.inc"

# ---------------------------------------------------------------- dedicated agent hostname
rm -f "$out/zz-cnapp-agent-host.conf"
if [ "$public" = true ] && [ -n "$agent_host" ] && [ "$agent_host" != "$main_host" ]; then
  cert=server
  [ -r /etc/nginx/tls/agent.crt ] && [ -r /etc/nginx/tls/agent.key ] && cert=agent
  cat >"$out/zz-cnapp-agent-host.conf" <<EOF
# Generated by $me: $agent_host serves the agent API only (any client, any network).
server {
  listen 8443 ssl;
  http2 on;
  server_name $agent_host;
  server_tokens off;
  ssl_certificate     /etc/nginx/tls/$cert.crt;
  ssl_certificate_key /etc/nginx/tls/$cert.key;
  ssl_protocols TLSv1.2 TLSv1.3;
  ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305;
  ssl_prefer_server_ciphers off;
  ssl_session_cache shared:SSL:10m;
  ssl_session_timeout 1d;
  ssl_session_tickets off;
  include /etc/nginx/conf.d/cnapp-server.inc;
  add_header X-Content-Type-Options "nosniff" always;
  add_header Referrer-Policy "no-referrer" always;
  add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;

  include /etc/nginx/conf.d/cnapp-agent-locations.inc;

  # Nothing else exists on this name (not even for internal clients).
  location / {
    return 404;
  }
}
EOF
  echo "$me: dedicated agent host $agent_host (certificate: $cert.crt)"
fi
# ---------------------------------------------------------------- public website (SITE_HOSTNAMES)
rm -f "$out/zz-cnapp-site.conf" "$out/cnapp-site-headers.inc"
if [ -n "$site_names" ]; then
  canonical=${site_names%% *}
  aliases=""
  [ "$canonical" != "$site_names" ] && aliases=${site_names#* }
  cert=server
  [ -r /etc/nginx/tls/site.crt ] && [ -r /etc/nginx/tls/site.key ] && cert=site
  edge_log="# $log_dir is not writable: no edge log"
  if [ -d "$log_dir" ] && [ -w "$log_dir" ]; then
    edge_log="access_log $log_dir/edge-access.log cnapp_edge_site if=\$cnapp_log_external;"
  fi
  # The page links to https://console.travound.com; point it at this install's console.
  sub=""
  if [ "$console_url" != "https://console.travound.com" ]; then
    sub="sub_filter 'https://console.travound.com' '$console_url';
  sub_filter_once off;"
  fi
  tls_block="ssl_certificate     /etc/nginx/tls/$cert.crt;
  ssl_certificate_key /etc/nginx/tls/$cert.key;
  ssl_protocols TLSv1.2 TLSv1.3;
  ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305;
  ssl_prefer_server_ciphers off;
  ssl_session_cache shared:SSL:10m;
  ssl_session_timeout 1d;
  ssl_session_tickets off;"
  logs="access_log /var/log/nginx/access.log main;
  $edge_log
  client_header_timeout 15s;
  keepalive_timeout 30s;"
  # Strict headers for every website response (repeated in each location: nginx
  # does not inherit add_header into a location that sets its own).
  cat >"$out/cnapp-site-headers.inc" <<'EOF'
# Generated by 25-cnapp-access.sh: public website security headers.
add_header Content-Security-Policy "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; connect-src 'self'; form-action 'self'; frame-ancestors 'none'; base-uri 'none'; object-src 'none'" always;
add_header Strict-Transport-Security "max-age=31536000" always;
add_header X-Content-Type-Options "nosniff" always;
add_header X-Frame-Options "DENY" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header Permissions-Policy "accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()" always;
add_header Cross-Origin-Opener-Policy "same-origin" always;
EOF
  {
    cat <<EOF
# Generated by $me: public website for $site_names (static site + POST /api/contact
# only, any client). Nothing else exists on these names: no console, no other API.
limit_req_zone \$binary_remote_addr zone=cnapp_site:10m rate=30r/s;
limit_req_zone \$binary_remote_addr zone=cnapp_contact:2m rate=6r/m;

# Plain HTTP: redirect to https://$canonical (same path).
server {
  listen 8080;
  server_name $site_names;
  server_tokens off;
  $logs
  location / {
    return 301 https://$canonical\$request_uri;
  }
}
EOF
    if [ -n "$aliases" ]; then
      cat <<EOF

# Other names: permanent redirect to https://$canonical.
server {
  listen 8443 ssl;
  http2 on;
  server_name $aliases;
  server_tokens off;
  $tls_block
  $logs
  add_header Strict-Transport-Security "max-age=31536000" always;
  location / {
    return 301 https://$canonical\$request_uri;
  }
}
EOF
    fi
    cat <<EOF

server {
  listen 8443 ssl;
  http2 on;
  server_name $canonical;
  server_tokens off;
  root /usr/share/nginx/site;
  index index.html;
  $tls_block
  $logs
  limit_req zone=cnapp_site burst=200 nodelay;
  client_max_body_size 32k;
  gzip on;
  gzip_types text/css application/javascript image/svg+xml;
  $sub
  include /etc/nginx/conf.d/cnapp-site-headers.inc;

  # "Request a demo" form: the only API on this name, POST only. The backend
  # always receives exactly /api/contact (never the client's raw path).
  location = /api/contact {
    include /etc/nginx/conf.d/cnapp-site-headers.inc;
    if (\$request_method != POST) { return 404; }
    limit_req zone=cnapp_contact burst=5 nodelay;
    client_body_timeout 15s;
    set \$site_contact_upstream "${backend%/}/api/contact";
    proxy_pass \$site_contact_upstream;
    proxy_http_version 1.1;
    proxy_set_header Host \$host;
    proxy_set_header X-Forwarded-Host \$host;
    # nginx is the edge: overwrite (never append to) client-supplied values.
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$remote_addr;
    proxy_set_header X-Forwarded-Proto https;
    proxy_set_header Cookie "";
    proxy_set_header Authorization "";
    proxy_connect_timeout 10s;
    proxy_read_timeout 60s;
    proxy_hide_header Set-Cookie;
    proxy_hide_header X-Content-Type-Options;
    proxy_hide_header X-Frame-Options;
    proxy_hide_header Referrer-Policy;
    proxy_hide_header Strict-Transport-Security;
    proxy_hide_header Content-Security-Policy;
    proxy_hide_header Permissions-Policy;
    proxy_hide_header Cross-Origin-Opener-Policy;
  }
  location /api/ {
    return 404;
  }

  # Fonts never change under the same name; other assets are revalidated daily.
  location /assets/fonts/ {
    include /etc/nginx/conf.d/cnapp-site-headers.inc;
    add_header Cache-Control "public, max-age=31536000, immutable" always;
    try_files \$uri =404;
  }
  location /assets/ {
    include /etc/nginx/conf.d/cnapp-site-headers.inc;
    add_header Cache-Control "public, max-age=86400" always;
    try_files \$uri =404;
  }
  # The page itself (and favicon.svg): always revalidated, so updates show at once.
  location / {
    include /etc/nginx/conf.d/cnapp-site-headers.inc;
    add_header Cache-Control "no-cache" always;
    try_files \$uri \$uri/ =404;
  }
}
EOF
  } >"$out/zz-cnapp-site.conf"
  echo "$me: public website for $site_names (canonical https://$canonical, certificate: $cert.crt, console links: $console_url)"
fi
echo "$me: public agent endpoint: $public; internal: ${CNAPP_INTERNAL_CIDRS:-127.0.0.0/8 only}; agent rate $rate_v burst $burst_v"
